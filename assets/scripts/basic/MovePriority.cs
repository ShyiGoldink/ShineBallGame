/// <summary>
/// "移动链"的优先级表。数值越大越先处理，**谁先处理谁就有权把这一帧的移动接手下来**
/// （处理完返回 false 就把后面的挡住，返回 true 就是"我不插手，往下传"）。
///
/// 为什么移动也要有一张表：球的移动以前是"每个移动组件自己 `_PhysicsProcess` 里推一步"，
/// 两个移动组件挂上去就会各推一步（双倍位移）。现在移动统一由球每帧发一个 `move_step`
/// 事件（只在**移动状态**发），移动组件按优先级订阅——**同一帧只有一个说了算**。
///
/// 想加"在普通移动之上再叠一点"的修正层：优先级排在普通移动**前面**、处理完返回 true 放行；
/// 想加"整段接管"的（冲刺、瞬移、苍/赫 牵引）：排在前面、处理完返回 false 挡住。
/// </summary>
public static class MovePriority
{
    /// <summary>普通移动（`1001`）：最低的一环，也是链条的收尾——它处理完就截断。</summary>
    public const int Normal = 0;

    /// <summary>苍/赫 牵引（`1002`）：排在普通移动前面，场上有苍/赫 时它说了算。</summary>
    public const int Jujutsu = 100;
}
